#Requires -Version 5.1
<#
  CorePilot — one-command testnet setup.

  Reads packages/contracts/.env.deploy, then:
    1. deploys the contracts to Elysium testnet,
    2. bootstraps a demo strategy (creator + executor bonds, oracle seed),
    3. writes apps/executor/.env and apps/web/.env with the deployed addresses.

  Usage (from the repo root):
    powershell -ExecutionPolicy Bypass -File scripts/setup-testnet.ps1
#>
$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot
$contracts = Join-Path $root "packages\contracts"
$envFile = Join-Path $contracts ".env.deploy"

if (-not (Test-Path $envFile)) {
    Write-Host "ERROR: missing $envFile" -ForegroundColor Red
    Write-Host "Copy packages/contracts/.env.deploy.example to .env.deploy and fill DEPLOYER_PRIVATE_KEY." -ForegroundColor Yellow
    exit 1
}

# Load .env.deploy into the process environment.
Get-Content $envFile | ForEach-Object {
    $line = $_.Trim()
    if ($line -eq "" -or $line.StartsWith("#")) { return }
    $idx = $line.IndexOf("=")
    if ($idx -lt 1) { return }
    $k = $line.Substring(0, $idx).Trim()
    $v = $line.Substring($idx + 1).Trim()
    [Environment]::SetEnvironmentVariable($k, $v, "Process")
}

if (-not $env:DEPLOYER_PRIVATE_KEY) {
    Write-Host "ERROR: DEPLOYER_PRIVATE_KEY is empty in $envFile" -ForegroundColor Red
    exit 1
}
if (-not $env:ELYSIUM_RPC_URL) { $env:ELYSIUM_RPC_URL = "https://testnet-rpc.elysium.kinetiq.xyz" }
if (-not $env:USDC_ADDRESS) { $env:USDC_ADDRESS = "0x7D29d8047B905000459c0E80c34a26CeedcB47b2" }

$forge = Join-Path $env:USERPROFILE ".foundry\bin\forge.exe"
if (-not (Test-Path $forge)) { $forge = "forge" }

Write-Host "==> Deploying contracts to Elysium testnet ($env:ELYSIUM_RPC_URL)..." -ForegroundColor Cyan
Push-Location $contracts
$out = & $forge script script/Deploy.s.sol:Deploy --rpc-url $env:ELYSIUM_RPC_URL --broadcast 2>&1
$code = $LASTEXITCODE
Pop-Location
$out | Write-Host
if ($code -ne 0) { Write-Host "ERROR: deploy failed (exit $code)" -ForegroundColor Red; exit 1 }

function Get-Addr([string]$name) {
    $m = $out | Select-String -Pattern ("$name:\s*(0x[0-9a-fA-F]{40})") | Select-Object -First 1
    if ($m) { return $m.Matches[0].Groups[1].Value } else { return "" }
}

$pilot      = Get-Addr "PilotToken"
$staking    = Get-Addr "PilotStaking"
$registry   = Get-Addr "StrategyRegistry"
$receipts   = Get-Addr "ExecutionReceiptRegistry"
$oracle     = Get-Addr "SignedMarketDataOracle"
$adapter    = Get-Addr "MockExecutionAdapter"
$controller = Get-Addr "ExecutionController"
$fee        = Get-Addr "FeeModule"

if (-not $controller) { Write-Host "ERROR: could not parse deployed addresses." -ForegroundColor Red; exit 1 }

$env:PILOT_TOKEN_ADDRESS = $pilot
$env:STAKING_ADDRESS = $staking
$env:STRATEGY_REGISTRY_ADDRESS = $registry
$env:EXECUTION_CONTROLLER_ADDRESS = $controller
$env:MARKET_DATA_ORACLE_ADDRESS = $oracle

Write-Host "==> Bootstrapping demo state (strategy + bonds + oracle seed)..." -ForegroundColor Cyan
Push-Location $contracts
$bout = & $forge script script/Bootstrap.s.sol:Bootstrap --rpc-url $env:ELYSIUM_RPC_URL --broadcast 2>&1
$bcode = $LASTEXITCODE
Pop-Location
$bout | Write-Host
if ($bcode -ne 0) { Write-Host "WARNING: bootstrap failed (exit $bcode) — deploy succeeded, continuing." -ForegroundColor Yellow }

# Write apps/executor/.env
$execEnv = @"
# Generated by scripts/setup-testnet.ps1 — TESTNET ONLY. Do not commit.
ELYSIUM_RPC_URL=$($env:ELYSIUM_RPC_URL)
ELYSIUM_CHAIN_ID=99801
HYPERLIQUID_API_URL=https://api.hyperliquid-testnet.xyz
EXECUTOR_POLL_MS=15000
EXECUTOR_ENABLE_LIVE_EXECUTION=true
EXECUTOR_PRIVATE_KEY=$($env:DEPLOYER_PRIVATE_KEY)
ORACLE_SIGNER_PRIVATE_KEY=$($env:DEPLOYER_PRIVATE_KEY)
PILOT_TOKEN_ADDRESS=$pilot
STAKING_ADDRESS=$staking
STRATEGY_REGISTRY_ADDRESS=$registry
EXECUTION_CONTROLLER_ADDRESS=$controller
FEE_MODULE_ADDRESS=$fee
MARKET_DATA_ORACLE_ADDRESS=$oracle
RECEIPT_REGISTRY_ADDRESS=$receipts
"@
Set-Content -Path (Join-Path $root "apps\executor\.env") -Value $execEnv -Encoding utf8

# Write apps/web/.env
$webEnv = @"
# Generated by scripts/setup-testnet.ps1
VITE_API_URL=http://localhost:8001
VITE_ELYSIUM_RPC_URL=$($env:ELYSIUM_RPC_URL)
VITE_ELYSIUM_CHAIN_ID=99801
VITE_PILOT_TOKEN_ADDRESS=$pilot
VITE_STAKING_ADDRESS=$staking
VITE_STRATEGY_REGISTRY_ADDRESS=$registry
VITE_EXECUTION_CONTROLLER_ADDRESS=$controller
VITE_MARKET_DATA_ORACLE_ADDRESS=$oracle
VITE_FEE_MODULE_ADDRESS=$fee
VITE_RECEIPT_REGISTRY_ADDRESS=$receipts
"@
Set-Content -Path (Join-Path $root "apps\web\.env") -Value $webEnv -Encoding utf8

Write-Host ""
Write-Host "==> DONE" -ForegroundColor Green
Write-Host "  PilotToken:             $pilot"
Write-Host "  PilotStaking:           $staking"
Write-Host "  StrategyRegistry:       $registry"
Write-Host "  ExecutionController:    $controller"
Write-Host "  SignedMarketDataOracle: $oracle"
Write-Host "  FeeModule:              $fee"
Write-Host ""
Write-Host "Wrote apps\executor\.env and apps\web\.env (git-ignored)." -ForegroundColor Green
Write-Host ""
Write-Host "Next:" -ForegroundColor Cyan
Write-Host "  pnpm --filter @corepilot/executor start   # runs the live loop"
Write-Host "  pnpm --filter @corepilot/web dev          # dashboard"
